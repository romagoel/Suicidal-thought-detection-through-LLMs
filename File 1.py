# Count classes dynamically
num_labels = len(set(train_labels + val_labels))  # Works for multiclass
results = {}

for name, model_name in model_names.items():
    print(f"🚀 Training {name}")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForSequenceClassification.from_pretrained(model_name, num_labels=num_labels).to(device)

    train_dataset = TextDataset(train_texts, train_labels, tokenizer)
    val_dataset = TextDataset(val_texts, val_labels, tokenizer)

    train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True)
    val_loader = DataLoader(val_dataset, batch_size=32)

    optimizer = AdamW(model.parameters(), lr=2e-5)
    lr_scheduler = get_scheduler("linear", optimizer=optimizer, num_warmup_steps=0,
                                  num_training_steps=len(train_loader)*5)

    best_f1 = 0
    patience = 2
    patience_counter = 0
    train_losses, val_losses = [], []

    for epoch in range(5):
        model.train()
        total_loss = 0
        for batch in tqdm(train_loader, desc=f"{name} Epoch {epoch+1}"):
            batch = {k: v.to(device) for k, v in batch.items()}
            outputs = model(**batch)
            loss = outputs.loss
            loss.backward()
            total_loss += loss.item()
            optimizer.step()
            lr_scheduler.step()
            optimizer.zero_grad()
        train_losses.append(total_loss / len(train_loader))

        model.eval()
        preds, true, val_loss = [], [], 0
        with torch.no_grad():
            for batch in val_loader:
                batch = {k: v.to(device) for k, v in batch.items()}
                outputs = model(**batch)
                val_loss += outputs.loss.item()
                logits = outputs.logits
                preds.extend(torch.argmax(logits, axis=1).cpu().numpy())
                true.extend(batch['labels'].cpu().numpy())

        val_losses.append(val_loss / len(val_loader))
        f1 = f1_score(true, preds, average='weighted')  # Multiclass-safe
        if f1 > best_f1:
            best_f1 = f1
            patience_counter = 0
            torch.save(model.state_dict(), f"best_model_{name}.pt")
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f"⏹️ Early stopping {name}")
                break

    acc = accuracy_score(true, preds)
    prec = precision_score(true, preds, average='weighted')
    rec = recall_score(true, preds, average='weighted')

    results[name] = {
        'accuracy': acc,
        'precision': prec,
        'recall': rec,
        'f1': f1,
        'train_loss': train_losses,
        'val_loss': val_losses
    }





